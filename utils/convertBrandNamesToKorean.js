function escapeRegExp(text) {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function convertBrandNamesToKorean(title) {
  if (typeof title !== "string") return title;

  for (const rules of brandRules) {
    // 긴 검색어부터 확인: NEW TORRENT → TORRENT → 토렌트
    const entries = Object.entries(rules)
      .filter(([keyword]) => keyword !== "")
      .sort(([a], [b]) => b.length - a.length);

    for (const [keyword, replacement] of entries) {
      // 같은 결과로 변환되는 표기들만 묶음
      const aliases = entries
        .filter(([, value]) => value === replacement)
        .map(([key]) => key);

      // 최종 표기의 한글명도 포함
      // 예: "뉴 토렌트(NEW TORRENT)" → "뉴 토렌트"
      const koreanName = replacement.match(/^(.+?)\([^()]+\)$/)?.[1];

      if (koreanName) aliases.push(koreanName);

      const aliasPattern = [...new Set(aliases)]
        .sort((a, b) => b.length - a.length)
        .map(escapeRegExp)
        .join("|");

      const pattern = new RegExp(
        [
          // 이미 변환된 표기는 통째로 처리
          escapeRegExp(replacement),

          // 영문(한글), 한글(영문) 형태 처리
          `(?:${aliasPattern})\\s*\\(\\s*(?:${aliasPattern})\\s*\\)`,

          // 현재 검색어
          escapeRegExp(keyword),
        ].join("|"),
        "i",
      );

      if (!pattern.test(title)) continue;

      // g 옵션이 없으므로 한 곳만 변환
      title = title.replace(pattern, () => replacement);

      // 일치했으면 같은 객체의 다른 규칙은 적용하지 않음
      break;
    }
  }

  return title;
}
